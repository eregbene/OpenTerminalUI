class MT5CandleRevisionORM(Base):
    """Immutable, append-only revision history for a canonical bar (Option A -- confirmed
    necessary: mt5_canonical_candles rows are upserted via db.merge() on every re-fetch, so a
    later fetch silently overwrites whatever OHLC the live engine actually decided against,
    with no way to recover the original value afterward -- proven directly against this
    deployment's own data on 2026-08-12: a single 30-day historical backfill stamped the same
    `updated_at` across ~364,000 already-live-captured rows).

    One row per MATERIALLY DIFFERENT observed OHLC for a given (provider, broker_symbol,
    timeframe, bar_timestamp) -- never updated after insert. `bar_timestamp` is the value
    exactly as reported by the provider (broker-server time for MT5, NEVER silently rewritten);
    `bar_timestamp_utc` is that same instant corrected using `broker_utc_offset_minutes` as
    detected at capture time -- every point-in-time comparison in replay.py uses ONLY this
    column, never the raw provider-labeled one. `finalized=True` marks a bar considered stable
    enough (per quality.is_finalized's age policy) that a differing re-fetch is no longer
    trusted to overwrite it -- see ingestion.py's write path for the enforcement."""

    __tablename__ = "mt5_candle_revisions"

    revision_id: Mapped[str] = mapped_column(String(160), primary_key=True)
    provider: Mapped[str] = mapped_column(String(32), nullable=False, index=True)
    canonical_symbol: Mapped[str] = mapped_column(String(32), nullable=False, index=True)
    broker_symbol: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    timeframe: Mapped[str] = mapped_column(String(16), nullable=False, index=True)
    bar_timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    bar_timestamp_utc: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    broker_utc_offset_minutes: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    observed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    revision_number: Mapped[int] = mapped_column(Integer, nullable=False, default=1)
    open: Mapped[float] = mapped_column(Float, nullable=False)
    high: Mapped[float] = mapped_column(Float, nullable=False)
    low: Mapped[float] = mapped_column(Float, nullable=False)
    close: Mapped[float] = mapped_column(Float, nullable=False)
    tick_volume: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    spread: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    real_volume: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    finalized: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False, index=True)
    # Set only on a revision observed AFTER the bar was already finalized (a value that differed
    # from the trusted finalized value, and was therefore NOT applied to mt5_canonical_candles)
    # -- an anomaly worth surfacing, never silently dropped.
    post_finalization_anomaly: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, default=utcnow, index=True)

    __table_args__ = (
        UniqueConstraint("provider", "broker_symbol", "timeframe", "bar_timestamp", "revision_number", name="uq_mt5_candle_revision"),
        Index("ix_mt5_candle_revision_lookup", "provider", "broker_symbol", "timeframe", "bar_timestamp", "observed_at"),
    )


