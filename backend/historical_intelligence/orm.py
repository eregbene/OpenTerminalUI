class HistoricalSetupOutcomeORM(Base):
    """One row per fingerprint (Part 3), computed EXCLUSIVELY from candles strictly AFTER
    entry_time -- never used for signal generation, only for labeling what happened next. See
    outcomes.py's module docstring for the exact walk-forward algorithm (reused, not
    reimplemented, from backend/brokers/mt5/outcome_resolver.py's shadow-candidate resolution:
    same R formula, same SL-touched-first tie-break when a single candle's range spans both
    levels)."""

    __tablename__ = "historical_setup_outcomes"

    outcome_id: Mapped[str] = mapped_column(String(160), primary_key=True)
    fingerprint_id: Mapped[str] = mapped_column(String(160), nullable=False, unique=True, index=True)

    # PENDING: future data insufficient to resolve yet (setup too recent). RESOLVED: reached a
    # terminal state. INSUFFICIENT_FUTURE_DATA: replay range simply doesn't extend far enough
    # (e.g. near the edge of ingested history) -- distinct from PENDING (which implies the setup
    # is *live-recent*), so callers never conflate "still open" with "we ran out of history".
    resolution_status: Mapped[str] = mapped_column(String(32), nullable=False, index=True, default="PENDING")

    outcome_r: Mapped[float | None] = mapped_column(Float, nullable=True)
